def test_eclipse_fraction_matches_the_circular_orbit_closed_form(
    epoch: datetime, one_day: list[eclipse.Eclipse]
) -> None:
    """The share of each orbit spent in shadow matches the textbook expression.

    ``f = (1/pi) arccos( sqrt(a^2 - Re^2) / (a cos beta) )`` is the standard circular-orbit,
    cylindrical-shadow eclipse fraction. It is the single strongest offline check available here
    because it ties the two halves of this module together: an error in the beta angle and an
    error in the shadow geometry would both have to conspire to keep this passing.

    The closed form assumes a circular orbit and ignores the Sun's angular size, so it is
    expected to sit a fraction of a percent away -- see the tolerance commentary above.
    """
    beta_rad = math.radians(eclipse.beta_angle(FIXTURE_TLE, epoch).value)
    expected = (
        math.acos(
            math.sqrt(SEMI_MAJOR_AXIS_KM**2 - EARTH_RADIUS_KM**2)
            / (SEMI_MAJOR_AXIS_KM * math.cos(beta_rad))
        )
        / math.pi
    )

    measured = one_day[0].orbit_fraction
    relative = abs(measured - expected) / expected

    assert relative <= CLOSED_FORM_FRACTION_TOLERANCE, (
        f"eclipse fraction {measured:.6f} disagrees with the closed form {expected:.6f} by "
        f"{relative:.3%} (tolerance {CLOSED_FORM_FRACTION_TOLERANCE:.0%})"
    )


def test_eclipses_are_internally_consistent(one_day: list[eclipse.Eclipse]) -> None:
    """Every eclipse enters, darkens, brightens, and exits, in that order.

    The umbra must be strictly nested inside the penumbra: entering total shadow before losing
    part of the Sun is geometrically impossible, and would mean the two boundary searches were
    paired the wrong way round.
    """
    assert one_day, "the ISS should be eclipsed on every revolution at this beta angle"

    for item in one_day:
        assert item.entry_utc < item.exit_utc
        assert item.duration_s > 0
        assert item.umbra_entry_utc is not None, "this orbit is nowhere near a grazing geometry"
        assert item.entry_utc < item.umbra_entry_utc < item.umbra_exit_utc < item.exit_utc
        assert item.umbra_duration_s < item.duration_s
        # Each field is rounded to a millisecond independently, so allow two of them.
        assert item.penumbra_duration_s == pytest.approx(
            item.duration_s - item.umbra_duration_s, abs=2e-3
        )
        # A shadow passage is a fraction of a revolution, never longer than one.
        assert 0.0 < item.orbit_fraction < 1.0
        assert item.duration_s == pytest.approx(item.orbit_fraction * ORBITAL_PERIOD_S, rel=1e-3)


def test_eclipses_are_chronological_and_disjoint(one_day: list[eclipse.Eclipse]) -> None:
    """Eclipses come back in order and do not overlap.

    Overlapping shadow intervals would mean an entry from one revolution had been paired with an
    exit from the next, which inflates a duration without producing any obviously wrong number.
    """
    for earlier, later in pairwise(one_day):
        assert earlier.exit_utc < later.entry_utc


def test_one_eclipse_occurs_per_revolution(one_day: list[eclipse.Eclipse]) -> None:
    """The eclipse count tracks the number of revolutions in the span.

    At a beta angle well inside the critical value the satellite is eclipsed on every orbit, so
    the count must follow the mean motion. A count far below it means eclipses are being missed
    by the coarse search step; far above it means boundaries are being double-counted.
    """
    assert abs(len(one_day) - MEAN_MOTION_REV_PER_DAY) <= 1.5, (
        f"{len(one_day)} eclipses in a day for an orbit that completes "
        f"{MEAN_MOTION_REV_PER_DAY:.3f} revolutions"
    )


def test_penumbra_is_short_but_never_zero(one_day: list[eclipse.Eclipse]) -> None:
    """Each eclipse has a brief partial phase at both edges.

    This is the check that a *conical* shadow model is actually in use. A cylindrical model --
    the common simplification -- makes the Sun a point source and collapses the penumbra to
    nothing, so a zero here means umbra and penumbra have silently become the same thing and
    every reported eclipse is about twelve seconds short at each end. The width follows from the
    Sun's half-degree angular size, which puts it at tens of seconds for a low orbit.
    """
    for item in one_day:
        assert 5.0 < item.penumbra_duration_s < 120.0, (
            f"penumbra of {item.penumbra_duration_s:.1f} s is not consistent with a conical "
            "shadow at low Earth orbit"
        )


def test_shadow_model_constants_are_in_the_units_the_module_claims() -> None:
    """The Earth and Sun radii are kilometres, not metres.

    A factor of a thousand in either radius would not raise. It would produce an eclipse
    computation that runs cleanly and returns numbers of the wrong length entirely -- an Earth
    the size of a city casts no shadow, and every eclipse would quietly vanish.
    """
    assert 6300.0 < eclipse.EARTH_RADIUS_KM < 6400.0
    assert 690000.0 < eclipse.SUN_RADIUS_KM < 700000.0
    # The Sun is roughly 109 Earth radii across; a wrong pairing of units breaks this ratio.
    assert 100.0 < eclipse.SUN_RADIUS_KM / eclipse.EARTH_RADIUS_KM < 115.0


def test_sun_position_is_about_one_astronomical_unit_away(epoch: datetime) -> None:
    """The solar ephemeris returns kilometres at roughly the right distance.

    Guards the one input to this module that comes from outside skyfield. A metres/kilometres slip
    here would put the Sun a thousand times closer, which changes its apparent size and therefore
    the penumbra, without changing the Sun's *direction* -- so beta would still look perfect.
    """
    distance_km = float(
        np.linalg.norm(eclipse._sun_gcrs_km(orbit.TIMESCALE.from_datetime(epoch))[:, 0])
    )
    assert 1.47e8 < distance_km < 1.53e8, f"Sun at {distance_km:.3e} km is not at 1 AU"


