def test_beta_angle_is_bounded_by_inclination_plus_obliquity(epoch: datetime) -> None:
    """|beta| can never exceed the orbit inclination plus Earth's axial tilt.

    The Sun stays within 23.44 deg of the equator, and the orbit normal is inclined by exactly
    the orbit inclination, so their angular separation -- and therefore beta -- is bounded. This
    is a hard geometric limit no orbit can violate, which makes it the cheapest possible catch
    for a swapped axis, a normal computed as ``v x r`` instead of ``r x v``, or a Sun vector left
    in the wrong frame. All of those produce values well outside the bound.
    """
    limit = INCLINATION_DEG + OBLIQUITY_DEG + 0.5

    for offset_days in range(0, 30, 3):
        beta = eclipse.beta_angle(FIXTURE_TLE, epoch + timedelta(days=offset_days))
        assert beta.unit == "deg"
        assert abs(beta.value) <= limit, (
            f"beta {beta.value:.3f} deg at epoch+{offset_days} d exceeds the geometric limit "
            f"{limit:.3f} deg for a {INCLINATION_DEG} deg orbit"
        )


def test_beta_angle_matches_the_closed_form_at_epoch(epoch: datetime) -> None:
    """The module agrees with the textbook beta identity at the element set's own epoch.

    ``sin(beta) = cos(dec) sin(i) sin(raan - ra) + sin(dec) cos(i)`` expresses beta purely in
    terms of the published orbital elements and the Sun's right ascension and declination. The
    inclination and node are read straight from the TLE text rather than from anything the module
    computed, so this is a genuinely separate route to the same number.

    Only the epoch is checked: the identity uses the *published* node, and a low orbit's node
    regresses several degrees a day, so the closed form goes stale almost immediately. That is a
    property of the shortcut, not of the module.
    """
    beta = eclipse.beta_angle(FIXTURE_TLE, epoch).value

    sun = get_sun(Time(epoch))
    inclination = math.radians(INCLINATION_DEG)
    node = math.radians(RAAN_DEG)

    closed_form = math.degrees(
        math.asin(
            math.cos(sun.dec.rad) * math.sin(inclination) * math.sin(node - sun.ra.rad)
            + math.sin(sun.dec.rad) * math.cos(inclination)
        )
    )

    assert abs(beta - closed_form) <= CLOSED_FORM_BETA_TOLERANCE_DEG, (
        f"beta {beta:.5f} deg disagrees with the closed form {closed_form:.5f} deg by "
        f"{abs(beta - closed_form):.5f} deg (tolerance {CLOSED_FORM_BETA_TOLERANCE_DEG} deg)"
    )


def test_beta_angle_tier_weakens_away_from_epoch(epoch: datetime) -> None:
    """Beta is derived at the element set's epoch and predicted anywhere else.

    Propagating is modelling, and a modelled value must not render like a measured one. Without
    this the trust taxonomy is decoration.
    """
    assert eclipse.beta_angle(FIXTURE_TLE, epoch).tier is Tier.DERIVED
    assert eclipse.beta_angle(FIXTURE_TLE, epoch + timedelta(days=1)).tier is Tier.PREDICTED


def test_beta_angle_receipt_states_frame_time_scale_and_uncertainty(epoch: datetime) -> None:
    """A beta angle carries everything needed to audit it."""
    receipt = eclipse.beta_angle(FIXTURE_TLE, epoch).receipt

    assert receipt.time_scale == "UTC"
    assert "GCRS" in receipt.frame, "beta angle is frame-dependent and must say which frame"
    assert receipt.dataset["sun_ephemeris"], "the solar ephemeris is an input and must be recorded"
    assert receipt.uncertainty["boundary_timing_error_s"] > 0


def test_naive_datetimes_are_rejected(epoch: datetime) -> None:
    """A datetime without a time zone has no time scale, so it is refused rather than assumed."""
    with pytest.raises(ValueError, match="timezone-aware"):
        eclipse.beta_angle(FIXTURE_TLE, epoch.replace(tzinfo=None))

    with pytest.raises(ValueError, match="timezone-aware"):
        eclipse.eclipse_intervals(FIXTURE_TLE, epoch.replace(tzinfo=None), days=1.0)


@pytest.mark.parametrize("days", [0.0, -1.0, 40.0])
def test_out_of_range_spans_are_rejected(epoch: datetime, days: float) -> None:
    """Empty, negative, and unboundedly long spans are refused rather than silently accepted."""
    with pytest.raises(ValueError, match="days must be"):
        eclipse.eclipse_intervals(FIXTURE_TLE, epoch, days=days)


