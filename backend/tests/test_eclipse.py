def test_summary_reports_the_worst_case_a_battery_must_survive(
    epoch: datetime, one_day: list[eclipse.Eclipse]
) -> None:
    """The summary's extremes are the extremes of the intervals it summarises.

    A battery is sized on the longest eclipse in the span, so a maximum that quietly reported a
    mean instead would undersize the cell by the difference -- here about half a minute of
    discharge on every orbit of the mission.
    """
    summary = eclipse.eclipse_summary(FIXTURE_TLE, epoch, days=1.0)

    assert summary["eclipse_count"].value == len(one_day)
    assert summary["max_eclipse_duration"].value == pytest.approx(
        max(item.duration_s for item in one_day), abs=1e-3
    )
    assert summary["min_eclipse_duration"].value == pytest.approx(
        min(item.duration_s for item in one_day), abs=1e-3
    )
    assert (
        summary["min_eclipse_duration"].value
        <= summary["mean_eclipse_duration"].value
        <= summary["max_eclipse_duration"].value
    )
    assert summary["max_umbra_duration"].value < summary["max_eclipse_duration"].value
    assert summary["max_eclipse_duration"].unit == "s"
    assert summary["max_orbit_fraction"].unit == "none"


def test_summary_values_are_predicted_and_carry_a_receipt(epoch: datetime) -> None:
    """Everything in a span summary is a prediction, because a span leaves the epoch.

    The beta angle at the start of the span is the one exception the taxonomy allows: when the
    span begins at the element set's own epoch it is derived, not predicted, and the summary must
    not launder that distinction away in either direction.
    """
    summary = eclipse.eclipse_summary(FIXTURE_TLE, epoch, days=1.0)

    for key in ("max_eclipse_duration", "min_eclipse_duration", "eclipse_count"):
        assert summary[key].tier is Tier.PREDICTED
        assert summary[key].receipt.frame
        assert summary[key].receipt.time_scale == "UTC"
        assert "conical" in summary[key].receipt.notes.lower()

    assert summary["beta_angle_at_start"].tier is Tier.DERIVED
    assert summary["beta_angle_at_end"].tier is Tier.PREDICTED


def test_a_span_with_no_complete_eclipse_reports_zeroes_rather_than_failing(
    epoch: datetime,
) -> None:
    """An eclipse-free span is a valid answer, and says so in its receipt.

    Full sun is a real operating season, not an error: it is when the power problem disappears and
    the thermal one arrives. Raising here would make the caller unable to distinguish it from a
    failure.
    """
    summary = eclipse.eclipse_summary(FIXTURE_TLE, epoch, days=1.0 / 1440.0)

    assert summary["eclipse_count"].value == 0
    assert summary["max_eclipse_duration"].value == 0.0
    assert summary["min_eclipse_duration"].value == 0.0
    assert "No complete eclipse" in summary["max_eclipse_duration"].receipt.notes


def test_partial_eclipses_at_the_span_boundaries_are_discarded(epoch: datetime) -> None:
    """An eclipse already underway when the span opens is omitted, not reported truncated.

    Starting the search a few minutes into a known eclipse must not produce an interval whose
    entry time is simply the start of the search. That would understate the duration and misstate
    the entry, and nothing downstream could tell.
    """
    known = eclipse.eclipse_intervals(FIXTURE_TLE, epoch, days=0.2)[0]
    midway = known.entry_utc + (known.exit_utc - known.entry_utc) / 2

    later = eclipse.eclipse_intervals(FIXTURE_TLE, midway, days=0.2)

    assert later, "the shortened span should still contain complete eclipses"
    assert all(item.entry_utc > known.exit_utc for item in later)


