@pytest.mark.parametrize(
    "sample", _reference_section("beta_angles"), ids=lambda s: f"+{s['offset_minutes']}min"
)
def test_beta_angle_matches_orekit(sample: dict[str, Any]) -> None:
    """skyfield/astropy and Orekit agree on the orbit-plane-to-Sun angle.

    Beta is the most frame-sensitive quantity this project computes, which is exactly why it is
    worth grading against an independent frame stack. A disagreement of a few hundredths of a
    degree points at the solar ephemeris; a disagreement near a third of a degree is the
    signature of TEME being mistaken for GCRF.
    """
    measured = eclipse.beta_angle(FIXTURE_TLE, _parse_utc(sample["epoch_utc"])).value
    difference = abs(measured - sample["beta_deg"])

    assert difference <= BETA_TOLERANCE_DEG, (
        f"beta disagreement at +{sample['offset_minutes']} min: {difference:.6f} deg "
        f"(tolerance {BETA_TOLERANCE_DEG} deg); skyfield {measured:.6f}, "
        f"orekit {sample['beta_deg']:.6f}"
    )


@pytest.mark.parametrize(
    "sample", _reference_section("beta_angles"), ids=lambda s: f"+{s['offset_minutes']}min"
)
def test_sun_direction_matches_orekit(sample: dict[str, Any]) -> None:
    """The two solar ephemerides point in the same direction, to within aberration.

    Checked separately from beta so a failure can be attributed rather than guessed at: if this
    passes and the beta test fails, the problem is in the orbit or the frame, not the Sun.
    """
    when = orbit.TIMESCALE.from_datetime(_parse_utc(sample["epoch_utc"]))

    measured = eclipse._sun_gcrs_km(when)[:, 0]
    measured = measured / np.linalg.norm(measured)

    expected = np.array(sample["sun_gcrf_m"])
    expected = expected / np.linalg.norm(expected)

    separation_arcsec = math.degrees(
        math.acos(min(1.0, max(-1.0, float(np.dot(measured, expected)))))
    ) * 3600.0

    assert separation_arcsec <= SUN_DIRECTION_TOLERANCE_ARCSEC, (
        f"solar ephemerides disagree by {separation_arcsec:.2f} arcsec at "
        f"+{sample['offset_minutes']} min (tolerance {SUN_DIRECTION_TOLERANCE_ARCSEC} arcsec)"
    )


@pytest.mark.parametrize(
    "expected", _reference_section("eclipses"), ids=lambda e: e["entry_utc"]
)
def test_eclipse_boundaries_match_orekit(expected: dict[str, Any]) -> None:
    """Every umbra and penumbra boundary agrees with Orekit's event detection.

    All four boundaries are checked rather than just the duration, because two errors of the same
    sign cancel in a duration: an eclipse shifted bodily by ten seconds has exactly the right
    length and entirely the wrong times.
    """
    reference = _reference_or_skip()
    span_start = _parse_utc(reference["span"]["start_utc"])

    measured = eclipse.eclipse_intervals(FIXTURE_TLE, span_start, days=reference["span"]["days"])
    entry_utc = _parse_utc(expected["entry_utc"])

    match = min(measured, key=lambda item: abs((item.entry_utc - entry_utc).total_seconds()))

    boundaries = [
        ("entry", match.entry_utc, entry_utc),
        ("exit", match.exit_utc, _parse_utc(expected["exit_utc"])),
        ("umbra entry", match.umbra_entry_utc, _parse_utc(expected["umbra_entry_utc"])),
        ("umbra exit", match.umbra_exit_utc, _parse_utc(expected["umbra_exit_utc"])),
    ]

    for label, mine, theirs in boundaries:
        difference = abs((mine - theirs).total_seconds())
        assert difference <= BOUNDARY_TOLERANCE_S, (
            f"{label} disagreement for the eclipse at {expected['entry_utc']}: "
            f"{difference:.3f} s (tolerance {BOUNDARY_TOLERANCE_S} s); "
            f"skyfield {mine.isoformat()}, orekit {theirs.isoformat()}"
        )

    assert abs(match.duration_s - expected["duration_s"]) <= BOUNDARY_TOLERANCE_S
    assert abs(match.umbra_duration_s - expected["umbra_duration_s"]) <= BOUNDARY_TOLERANCE_S


def test_reference_pins_the_same_shadow_model_the_module_uses() -> None:
    """Guard: the two sides of the differential test model the same physical situation.

    Without this the whole tier-3 family is vacuous in a way that is invisible. If someone changed
    the Earth radius in `science.eclipse` and regenerated nothing, or changed the generator and
    not the module, the boundary comparisons would be measuring a deliberate modelling difference
    and calling it accuracy -- while a genuine 4 km error hid inside the widened residual. This
    is the eclipse family's equivalent of `test_teme_and_gcrf_are_actually_different`.
    """
    model = _reference_or_skip()["model"]

    assert model["earth_radius_m"] == pytest.approx(eclipse.EARTH_RADIUS_KM * 1e3, abs=1e-3)
    assert model["sun_radius_m"] == pytest.approx(eclipse.SUN_RADIUS_KM * 1e3, abs=1e-3)
    assert model["earth_flattening"] == 0.0, (
        "the reference must use a spherical Earth to match the module; an oblate one would make "
        "the comparison measure a modelling choice rather than an implementation"
    )


