"""Tests for eclipse geometry and beta angle.

Two tiers run here, and .agent/test.md is emphatic that they are not interchangeable.

**Tier 1 -- analytic.** Closed-form identities that hold for any orbit: the beta angle written in
terms of the published inclination and right ascension of the ascending node, and the textbook
circular-orbit eclipse fraction. These catch unit errors, sign errors, and swapped axes, and they
run offline on every commit. They are *not* an accuracy claim -- their tolerances are wide enough
to absorb the mean-element and frame approximations the closed forms make.

**Tier 3 -- differential against Orekit.** The headline truth source. It compares beta angles and
umbra/penumbra boundary times against `tests/reference/eclipse.json`, generated by
`tools/reference/generate_eclipse.py`. Those tests **skip when the reference is absent**, in the
same way `test_frames.py` does, so a checkout that has never run the generator still gets a green
tier-1 suite rather than a wall of failures.

Everything runs against a frozen element set and astropy's built-in solar ephemeris, so no test
here touches the network.
"""

from __future__ import annotations

import json
import math
import time
from datetime import UTC, datetime, timedelta
from itertools import pairwise
from pathlib import Path
from typing import Any

import numpy as np
import pytest
from astropy import units as u
from astropy.constants import GM_earth
from astropy.coordinates import get_sun
from astropy.time import Time

from science import catalog, eclipse, orbit
from science.provenance import Tier

REFERENCE_PATH = Path(__file__).parent / "reference" / "eclipse.json"

# ISS (ZARYA), frozen so results are reproducible. The same element set the reference generators
# use, so a tier-1 and a tier-3 failure describe the same orbit.
FIXTURE_TLE = catalog.TLE(
    name="ISS (ZARYA)",
    line1="1 25544U 98067A   24001.50000000  .00016717  00000-0  30150-3 0  9004",
    line2="2 25544  51.6416 247.4627 0006703 130.5360 325.0288 15.49815310 10000",
    norad_id=25544,
    source="test-fixture",
    fetched_at_unix=time.time(),
)

# Read straight out of the TLE text rather than from anything the module under test computes, so
# the closed-form checks below stay independent of it. Columns are fixed by the TLE format.
INCLINATION_DEG = float(FIXTURE_TLE.line2[8:16])
RAAN_DEG = float(FIXTURE_TLE.line2[17:25])
MEAN_MOTION_REV_PER_DAY = float(FIXTURE_TLE.line2[52:63])

ORBITAL_PERIOD_S = 86400.0 / MEAN_MOTION_REV_PER_DAY

# Earth's axial tilt. The Sun's declination is bounded by it, which is what bounds the beta angle.
OBLIQUITY_DEG = 23.44

# Earth's equatorial radius, stated here rather than read from the module so the closed-form
# check below does not depend on the value it is checking. IERS 2010, in km.
EARTH_RADIUS_KM = 6378.1366

# Semi-major axis from Kepler's third law and the published mean motion. This is a mean element,
# so it sits about 10 km away from the instantaneous radius; the closed-form tolerances below
# allow for that.
SEMI_MAJOR_AXIS_KM = (
    GM_earth.to_value(u.km**3 / u.s**2) * (ORBITAL_PERIOD_S / (2.0 * math.pi)) ** 2
) ** (1.0 / 3.0)

# ---------------------------------------------------------------------------------------------
# Tolerances, each measured before being set.
# ---------------------------------------------------------------------------------------------

# Closed-form beta angle vs the module, at the element set's own epoch: measured 0.276 deg.
# The residual is dominated by a real modelling difference, not by an error -- a TLE's mean
# elements are referenced to the true equator and equinox of date (TEME), while the module works
# in GCRS, and precession has separated the two by roughly 0.34 deg by 2024. One degree leaves
# 3.6x headroom over that while sitting an order of magnitude below any defect this can catch: a
# sign error on the declination term, a degrees/radians slip, or inclination and node swapped all
# move beta by tens of degrees.
CLOSED_FORM_BETA_TOLERANCE_DEG = 1.0

# Closed-form circular-orbit eclipse fraction vs the module: measured 0.59% relative. The closed
# form assumes a circular orbit and a cylindrical shadow, both of which the module deliberately
# does not; 2% leaves 3.4x headroom. This is a gross-error check, not an accuracy claim -- the
# differential test below is what measures accuracy.
CLOSED_FORM_FRACTION_TOLERANCE = 0.02

# Beta angle vs Orekit. Budgeted from the one known modelling difference between the two:
# astropy's get_sun returns the Sun's *apparent* position and Orekit's returns its *geometric*
# position, which differ by about 21 arcsec of annual aberration -- measured as 0.0047 deg of
# beta. 0.02 deg leaves 4x headroom over that, and sits 17x below the ~0.34 deg signature of a
# TEME/GCRF frame mix-up, which is the defect this exists to catch.
BETA_TOLERANCE_DEG = 0.02

# Sun direction vs Orekit, reported separately so a beta failure can be attributed. The measured
# apparent-vs-geometric separation is 20.8 arcsec; 30 arcsec accommodates it without hiding a
# real ephemeris or frame problem, which would be arcminutes or worse.
SUN_DIRECTION_TOLERANCE_ARCSEC = 30.0

# Eclipse boundary times vs Orekit. Measured contributions:
#     apparent-vs-geometric Sun     0.11 s      (the only known modelling difference)
#     sgp4-vs-Orekit propagation    < 0.001 s   (see test_propagation.py: sub-millimetre)
# Defects this must still catch, measured on this orbit by perturbing the model:
#     mean Earth radius instead of equatorial (6371 km)   3.8 s per boundary
#     penumbra merged into umbra (cylindrical shadow)    11.6 s per boundary
# Two seconds sits 18x above the known difference and safely below both defects.
BOUNDARY_TOLERANCE_S = 2.0


@pytest.fixture(scope="module")
def epoch() -> datetime:
    """The fixture element set's own epoch, in UTC."""
    return orbit.tle_epoch(FIXTURE_TLE)


@pytest.fixture(scope="module")
def one_day(epoch: datetime) -> list[eclipse.Eclipse]:
    """Every complete eclipse in the day following the epoch.

    Module-scoped because each search propagates the orbit a few hundred times; recomputing it
    per test would dominate the suite's runtime for no added coverage.
    """
    return eclipse.eclipse_intervals(FIXTURE_TLE, epoch, days=1.0)


def _reference() -> dict[str, Any]:
    """Load the committed Orekit eclipse reference."""
    return json.loads(REFERENCE_PATH.read_text(encoding="utf-8"))


def _reference_or_skip() -> dict[str, Any]:
    """Return the reference document, or skip the calling test if it has not been generated."""
    if not REFERENCE_PATH.exists():
        pytest.skip("eclipse.json not generated; run tools/reference/generate_eclipse.py")
    return _reference()


def _reference_section(key: str) -> list[dict[str, Any]]:
    """Return one list from the reference, or an empty list, for parametrizing tests."""
    if not REFERENCE_PATH.exists():
        return []
    return _reference()[key]


def _parse_utc(stamp: str) -> datetime:
    """Parse an Orekit ISO-8601 timestamp as a timezone-aware UTC datetime.

    Orekit writes UTC without an offset marker, so attaching the zone here is what stops the
    comparison from silently mixing a naive datetime with an aware one.

    Args:
        stamp: Timestamp as the generator wrote it.

    Returns:
        The same instant, tagged UTC.
    """
    return datetime.fromisoformat(stamp.rstrip("Z")).replace(tzinfo=UTC)


