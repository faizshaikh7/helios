def test_reference_beta_angles_actually_vary() -> None:
    """Guard: the reference records a moving Sun, not a frozen one.

    If the generator evaluated the Sun at a single fixed date, every beta sample would be
    identical and the beta tests would pass while checking nothing about time handling. Beta
    drifts several degrees a day at low Earth orbit as the node regresses, so a span of a day must
    show a clear spread.
    """
    samples = _reference_or_skip()["beta_angles"]
    spread = max(s["beta_deg"] for s in samples) - min(s["beta_deg"] for s in samples)

    assert spread > 1.0, (
        f"reference beta angles span only {spread:.4f} deg over a day; the Sun or the orbit plane "
        "is not being advanced with time"
    )


